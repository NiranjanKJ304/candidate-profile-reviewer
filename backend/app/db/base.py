"""Declarative base, constraint naming convention and shared column mixins/types.

Domain models live in :mod:`app.models` and register on :class:`Base`; Alembic's
``env.py`` imports that package so autogenerate sees every table.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterable
from datetime import datetime
from enum import StrEnum

from sqlalchemy import JSON, DateTime, Enum, MetaData, Uuid, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names keep Alembic migrations stable across databases.
# ``column_0_N_name`` joins all columns, so composite constraints get unique names.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

#: JSON column type: JSONB on PostgreSQL (indexable, binary), plain JSON elsewhere.
JsonDocument = JSON().with_variant(JSONB(), "postgresql")


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    """UUID primary key generated by the application, with a database-side fallback.

    ``gen_random_uuid()`` is built into PostgreSQL 13+, so rows inserted outside the
    ORM (migrations, manual SQL) also get a key.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )


class TimestampMixin:
    """UTC creation/update timestamps, set by the database."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


def _enum_values(members: Iterable[StrEnum]) -> list[str]:
    return [member.value for member in members]


def string_enum(enum_cls: type[StrEnum], name: str, length: int = 20) -> Enum:
    """Store a ``StrEnum`` as VARCHAR(length) + CHECK constraint (not a native PG enum).

    Values (not member names) are persisted, so the database holds e.g. ``"pending"``.
    The CHECK constraint is named ``ck_<table>_<name>`` by the naming convention.
    """
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=length,
        values_callable=_enum_values,
        validate_strings=True,
    )
